# 11_data_empty
# 목적: data.bin 이 0 바이트여도 데이터 영역 1,024 바이트는 0 으로 초기화되고 data.out 은 1,024 바이트. 0x0a/0x0d 바이트를 바이너리로 정확히 기록하는지(텍스트 모드 줄바꿈 변환 금지) 확인.
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000
0x00040004  0x2000a103  lw   x2, 512(x1)      # 초기화된 0
0x00040008  0x00d10113  addi x2, x2, 0x0d     # 0x0000000d
0x0004000c  0x0020a023  sw   x2, 0(x1)        # 0d 00 00 00
0x00040010  0x00a00193  addi x3, x0, 0x0a
0x00040014  0x3e30ae23  sw   x3, 1020(x1)     # 0a 00 00 00 (마지막 워드)
0x00040018  0x0a0d1237  lui  x4, 0x0a0d1      # 하위 12비트 0xa0d >= 0x800 이므로 상위 +1
0x0004001c  0xa0d20213  addi x4, x4, -0x5f3   # 0x0a0d1000 - 0x5f3 = 0x0a0d0a0d
0x00040020  0x0040a223  sw   x4, 4(x1)        # 0d 0a 0d 0a
0x00040024  0x00000000  .word 0               # 0x00040024
