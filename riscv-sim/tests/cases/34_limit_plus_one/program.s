# 34_limit_plus_one
# 목적: 필요한 실행 수가 정확히 1,000,001 개(= 3 + 2 * 499999). 1,000,000 번째로 addi 를 실행한 뒤 다음 fetch 는 지원 명령어 bne -> 실행하지 않고 비정상 종료(종료 코드 2). 한도 비교를 > 로 잘못 쓰면 bne 까지 실행되어 정상 종료가 되어 버린다.
#
# 주소        기계어      어셈블리
0x00040000  0x0007a0b7  lui  x1, 0x7a
0x00040004  0x11f08093  addi x1, x1, 0x11f    # 499999
0x00040008  0x00000013  nop                   # 실행 수 +1
0x0004000c  0xfff08093  loop: addi x1, x1, -1      # 1,000,000 번째 실행 = 마지막 반복의 addi
0x00040010  0xfe009ee3  bne  x1, x0, loop     # 1,000,001 번째 -> 실행하지 않고 비정상 종료
0x00040014  0x00000000  .word 0
