# 04_add_sub_wrap
# 목적: add/sub 결과를 하위 32비트로 유지(오버플로 무시, 음수는 2의 보수)하는지 확인.
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000      # x1 = 0x10000000
0x00040004  0x80000137  lui  x2, 0x80000      # x2 = 0x80000000
0x00040008  0xfff10113  addi x2, x2, -1       # x2 = 0x7fffffff (INT_MAX)
0x0004000c  0x00100193  addi x3, x0, 1        # x3 = 1
0x00040010  0x00310233  add  x4, x2, x3       # 0x7fffffff + 1 = 0x80000000 (부호 오버플로, 예외 없음)
0x00040014  0x0040a023  sw   x4, 0(x1)
0x00040018  0x403002b3  sub  x5, x0, x3       # 0 - 1 = -1 = 0xffffffff
0x0004001c  0x0050a223  sw   x5, 4(x1)
0x00040020  0x00420333  add  x6, x4, x4       # 0x80000000 * 2 = 0x1_00000000 -> 하위 32비트 0x00000000
0x00040024  0x0060a423  sw   x6, 8(x1)
0x00040028  0x005283b3  add  x7, x5, x5       # 0xffffffff * 2 = 0x1_fffffffe -> 0xfffffffe
0x0004002c  0x0070a623  sw   x7, 12(x1)
0x00040030  0x40320433  sub  x8, x4, x3       # 0x80000000 - 1 = 0x7fffffff
0x00040034  0x0080a823  sw   x8, 16(x1)
0x00040038  0x404184b3  sub  x9, x3, x4       # 1 - 0x80000000 = -2147483647 -> 0x80000001
0x0004003c  0x0090aa23  sw   x9, 20(x1)
0x00040040  0x00000000  .word 0               # 0x00040040
