# 03_x0_hardwired
# 목적: x0 에 대한 쓰기(addi, lui, add, sub, lw)가 모두 무시되고 x0 를 읽으면 항상 0 인지 확인.
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000      # x1 = 0x10000000
0x00040004  0x00500013  addi x0, x0, 5        # 무시
0x00040008  0xfffff037  lui  x0, 0xfffff      # 무시
0x0004000c  0x00700113  addi x2, x0, 7        # x2 = 0 + 7 = 7
0x00040010  0x00210033  add  x0, x2, x2       # 무시
0x00040014  0x40200033  sub  x0, x0, x2       # 무시
0x00040018  0x0000a003  lw   x0, 0(x1)        # 메모리 값 0x11223344 를 읽지만 무시
0x0004001c  0x0000a223  sw   x0, 4(x1)        # [+4] = 0 (0xdeadbeef 를 덮어씀)
0x00040020  0x002001b3  add  x3, x0, x2       # x3 = 0 + 7 = 7
0x00040024  0x0030a423  sw   x3, 8(x1)        # [+8] = 7 (0xffffffff 를 덮어씀)
0x00040028  0x00000000  .word 0               # 0x00040028
