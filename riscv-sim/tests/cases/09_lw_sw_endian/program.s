# 09_lw_sw_endian
# 목적: little-endian lw/sw. 78 56 34 12 -> 0x12345678, 저장 시 하위 바이트부터. 데이터 영역 첫 워드(0x10000000)와 마지막 워드(0x100003fc), 음수 오프셋.
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000      # x1 = 0x10000000
0x00040004  0x0000a103  lw   x2, 0(x1)        # 78 56 34 12 -> 0x12345678
0x00040008  0x0040a183  lw   x3, 4(x1)        # ef be ad de -> 0xdeadbeef
0x0004000c  0x3fc0a203  lw   x4, 1020(x1)     # 01 02 03 04 -> 0x04030201 (마지막 워드)
0x00040010  0x0020a823  sw   x2, 16(x1)       # [+16] = 78 56 34 12
0x00040014  0x40008293  addi x5, x1, 1024     # x5 = 0x10000400 (데이터 영역 끝 다음 주소)
0x00040018  0xfe32ae23  sw   x3, -4(x5)       # [0x100003fc] = ef be ad de
0x0004001c  0xc042a023  sw   x4, -1024(x5)    # [0x10000000] = 01 02 03 04
0x00040020  0x0080a303  lw   x6, 8(x1)        # 00 00 00 80 -> 0x80000000
0x00040024  0xfff30393  addi x7, x6, -1       # 0x7fffffff
0x00040028  0x0070aa23  sw   x7, 20(x1)       # [+20] = ff ff ff 7f
0x0004002c  0x00000000  .word 0               # 0x0004002c
