# 14_blt_bge_signed
# 목적: blt/bge 는 부호 있는 비교. 0xffffffff(-1) < 1 이므로 blt 분기. INT_MIN/INT_MAX, 같은 값. (부호 없는 비교로 잘못 구현하면 결과가 0x99 가 된다.)
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000
0x00040004  0xfff00113  addi x2, x0, -1       # 0xffffffff = -1
0x00040008  0x00100193  addi x3, x0, 1        # 1
0x0004000c  0x80000237  lui  x4, 0x80000      # 0x80000000 = INT_MIN
0x00040010  0xfff20293  addi x5, x4, -1       # 0x7fffffff = INT_MAX
0x00040014  0x00000513  addi x10, x0, 0
0x00040018  0x00314463  blt  x2, x3, A        # -1 < 1 참 -> 분기
0x0004001c  0x00156513  ori  x10, x10, 1
0x00040020  0x00315463  A:   bge  x2, x3, B        # -1 >= 1 거짓 -> 진행: bit1
0x00040024  0x00256513  ori  x10, x10, 2
0x00040028  0x0021c463  B:   blt  x3, x2, C        # 1 < -1 거짓 -> 진행: bit2
0x0004002c  0x00456513  ori  x10, x10, 4
0x00040030  0x0021d463  C:   bge  x3, x2, D        # 1 >= -1 참 -> 분기
0x00040034  0x00856513  ori  x10, x10, 8
0x00040038  0x00524463  D:   blt  x4, x5, E        # INT_MIN < INT_MAX 참 -> 분기
0x0004003c  0x01056513  ori  x10, x10, 16
0x00040040  0x00525463  E:   bge  x4, x5, F        # INT_MIN >= INT_MAX 거짓 -> 진행: bit5
0x00040044  0x02056513  ori  x10, x10, 32
0x00040048  0x0031d463  F:   bge  x3, x3, G        # 1 >= 1 참(같음) -> 분기
0x0004004c  0x04056513  ori  x10, x10, 64
0x00040050  0x0031c463  G:   blt  x3, x3, H        # 1 < 1 거짓 -> 진행: bit7
0x00040054  0x08056513  ori  x10, x10, 128
0x00040058  0x00a0a023  H:   sw   x10, 0(x1)       # 2 + 4 + 32 + 128 = 166 = 0xa6
0x0004005c  0x00000000  .word 0               # 0x0004005c
