# 13_beq_bne
# 목적: beq/bne 의 분기/비분기. 분기하면 다음 ori 를 건너뛴다. x10 비트가 1 = 그 ori 가 실행됨.
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000
