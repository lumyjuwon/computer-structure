# 07_lui
# 목적: lui 는 imm20<<12 를 쓰고 하위 12비트를 0 으로 만든다. lui+addi 로 32비트 상수 만들기(하위 12비트가 0x800 이상이면 상위를 +1 하고 음수 addi).
#
# 주소        기계어      어셈블리
0x00040000  0x100000b7  lui  x1, 0x10000
0x00040004  0xfffff137  lui  x2, 0xfffff      # 0xfffff000
0x00040008  0x000011b7  lui  x3, 0x1          # 0x00001000
0x0004000c  0x12346237  lui  x4, 0x12346
0x00040010  0xfff20213  addi x4, x4, -1       # 0x12346000 - 1 = 0x12345fff
0x00040014  0x800002b7  lui  x5, 0x80000      # 0x80000000
0x00040018  0xdeadc337  lui  x6, 0xdeadc
0x0004001c  0xeef30313  addi x6, x6, -0x111   # 0xdeadc000 - 0x111 = 0xdeadbeef
0x00040020  0x7ff00393  addi x7, x0, 0x7ff    # x7 = 0x000007ff
0x00040024  0x543213b7  lui  x7, 0x54321      # 하위 비트까지 덮어씀 -> 0x54321000 (0x543217ff 아님)
0x00040028  0x0020a023  sw   x2, 0(x1)
0x0004002c  0x0030a223  sw   x3, 4(x1)
0x00040030  0x0040a423  sw   x4, 8(x1)
0x00040034  0x0050a623  sw   x5, 12(x1)
0x00040038  0x0060a823  sw   x6, 16(x1)
0x0004003c  0x0070aa23  sw   x7, 20(x1)
0x00040040  0x00000000  .word 0               # 0x00040040
